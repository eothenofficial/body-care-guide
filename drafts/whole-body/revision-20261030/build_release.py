def apply_reviewed_patches(chapters):
    """Apply immutable literal patches in memory; reruns never compound edits."""
    by_entry = {e['id']:e for c in chapters for e in c['entries']}
    by_chapter = {c['id']:c for c in chapters}
    by_unit = {u['id']:u for c in chapters for u in c['units']}
    patches = read_json(HERE/'prose-patches.json')['patches']
    for name in ['head-reader-patches.json','extra-fields-patches-head.json','extra-fields-patches-body.json']:
        patches += read_json(HERE/name)['patches']
    for patch in patches:
        target = {'entry':by_entry,'chapter':by_chapter,'unit':by_unit}[patch['target']][patch['id']]
        keys = patch['field'].split('.')
        for key in keys[:-1]: target = target[key]
        key = keys[-1]
        if target[key].count(patch['old']) != 1:
            raise ValueError('Ambiguous or stale prose patch: '+patch['id']+' '+patch['field'])
        target[key] = target[key].replace(patch['old'],patch['new'])
    scopes = read_json(HERE/'audience-overrides.json')
    records = scopes['entries']
    if isinstance(records,list): records = {e['id']:e['audience'] for e in records}
    if set(records) != set(by_entry): raise ValueError('Audience review must cover all authored entries')
    for eid,audience in records.items(): by_entry[eid]['audience'] = copy.deepcopy(audience)
    return chapters


